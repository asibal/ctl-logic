"""Generate custom app fonts (e.g. FONT_XL) and append them to felucca_font.h.
Called from fm1.toml: gen = ["tools/gen_app_fonts.py {gen}/felucca_font.h"]
"""
import sys
from pathlib import Path

# Add base/tools to sys.path to reuse gen_font's render logic and font paths
APP_DIR = Path(__file__).resolve().parents[1]
ROOT_DIR = APP_DIR.parent
BASE_TOOLS = ROOT_DIR / "base" / "tools"
sys.path.insert(0, str(BASE_TOOLS))

import gen_font

CUSTOM_SIZES = [
    ("XL", "BarlowSemiCondensed-Bold.ttf", 60, 1, False, 32, 95),
]

def main(header_path):
    lines = [
        "",
        "/* Generated by app/tools/gen_app_fonts.py */",
    ]
    for name, ttf, px, scale, pixel, first, last in CUSTOM_SIZES:
        h, glyphs = gen_font.render(ttf, px, scale, pixel, first, last)
        data, offs = [], []
        for adv, bw, g in glyphs:
            offs.append(len(data))
            for y in range(h):
                row = g[y * bw:(y + 1) * bw] + [0]
                for x in range(0, bw, 2):
                    data.append((row[x] << 4) | row[x + 1])
        assert len(data) < 65536
        lines.append(f"static const uint8_t FONT_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t FONT_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t FONT_{name}_ADV[{len(glyphs)}] = {{" +
                     ", ".join(str(a) for a, _, _ in glyphs) + "};")
        lines.append(f"static const uint8_t FONT_{name}_BW[{len(glyphs)}] = {{" +
                     ", ".join(str(b) for _, b, _ in glyphs) + "};")
        lines.append(f"static const felucca_font_t FONT_{name} = {{ {h}, {gen_font.PAD * scale}, {first}, {last}, "
                     f"FONT_{name}_ADV, FONT_{name}_BW, FONT_{name}_OFF, FONT_{name}_DATA }};")
        lines.append("")
        print(f"app custom font {name}: {ttf} {px}px h {h}, digit adv {glyphs[ord('0') - first][0]}, {len(data)} B")

    target = Path(header_path)
    with open(target, "a") as f:
        f.write("\n".join(lines) + "\n")

if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("Usage: gen_app_fonts.py <path_to_felucca_font.h>")
    main(sys.argv[1])
